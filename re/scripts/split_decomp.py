"""Split a Ghidra decompile dump (ExportAll.java output) into per-module files.

Usage: split_decomp.py <decomp.c> <outdir>

Functions are assigned to modules by address range (see docs/reverse-engineering.md).
Each module file is sorted by address; an index.tsv lists address, name, module.
"""
import os, re, sys

MODULES = [
    (0x401000, 0x410000, "ecmd_script_commands"),
    (0x410000, 0x420000, "camera_input_sound"),
    (0x420000, 0x424a00, "evt_script_vm"),
    (0x424a00, 0x427000, "sfx_miles"),
    (0x427000, 0x42b000, "txt_timer_vfs"),
    (0x42b000, 0x459000, "d3_engine"),
    (0x459000, 0x46c000, "d2_ui"),
    (0x46c000, 0x4f0000, "game_logic"),
    (0x4f0000, 0x52c000, "game_manager_saveload"),
    (0x52c000, 0x5c0000, "messages_gameplay_screens"),
    (0x5c0000, 0x605000, "menus_options_network"),
    (0x605000, 0x615000, "crt"),
]

def module_of(addr):
    for lo, hi, name in MODULES:
        if lo <= addr < hi:
            return name
    return "other"

src, out = sys.argv[1], sys.argv[2]
os.makedirs(out, exist_ok=True)
chunks = {}
index = []
cur = None
with open(src, encoding="latin1") as f:
    for line in f:
        m = re.match(r"// ==== FUNCTION ([0-9a-f]+) (\S+)", line)
        if m:
            addr = int(m.group(1), 16)
            mod = module_of(addr)
            cur = [addr, []]
            chunks.setdefault(mod, []).append(cur)
            index.append((addr, m.group(2), mod))
        if cur is not None:
            cur[1].append(line)
for mod, funcs in chunks.items():
    funcs.sort(key=lambda c: c[0])
    with open(os.path.join(out, mod + ".c"), "w", encoding="latin1") as f:
        f.write(f"// Ghidra decompilation of GildeGold_TL.exe, module '{mod}'.\n"
                "// Generated by re/decompile.sh -- do not commit (derived from copyrighted code).\n\n")
        for _, lines in funcs:
            f.writelines(lines)
with open(os.path.join(out, "index.tsv"), "w") as f:
    for addr, name, mod in sorted(index):
        f.write(f"{addr:08x}\t{name}\t{mod}\n")
for mod in sorted(chunks):
    print(f"{mod:28} {len(chunks[mod]):5} functions")
